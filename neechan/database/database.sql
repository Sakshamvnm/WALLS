CREATE DATABASE IF NOT EXISTS neechan
	CHARACTER SET utf8mb4
	COLLATE utf8mb4_unicode_ci;

USE neechan;

CREATE TABLE IF NOT EXISTS users (
	id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	name VARCHAR(120) NOT NULL,
	date_of_birth DATE NOT NULL,
	email VARCHAR(254) NOT NULL,
	password_hash VARCHAR(255) NOT NULL,
	role ENUM('user', 'admin') NOT NULL DEFAULT 'user',
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (id),
	UNIQUE KEY users_email_unique (email)
) ENGINE=InnoDB;

ALTER TABLE users
	ADD COLUMN IF NOT EXISTS role ENUM('user', 'admin') NOT NULL DEFAULT 'user' AFTER password_hash;

CREATE TABLE IF NOT EXISTS posts (
	id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
	user_id BIGINT UNSIGNED NOT NULL,
	body TEXT NOT NULL,
	photo MEDIUMBLOB NULL,
	photo_mime VARCHAR(50) NULL,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
	PRIMARY KEY (id),
	KEY posts_user_created (user_id, created_at),
	CONSTRAINT posts_user_fk FOREIGN KEY (user_id)
		REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB;
